export function ExplorePage({
  section,
  language,
}: {
  section: keyof typeof explorePages;
  language: Language;
}) {
  const page = explorePages[section];
  const i = language === "fa" ? 1 : 0;
  return (
    <article className="explore-page container">
      <nav aria-label={i ? "مسیر صفحه" : "Breadcrumb"}>
        <a href="/">{i ? "خانه" : "Home"}</a> /{" "}
        <span aria-current="page">{page.title[i]}</span>
      </nav>
      <header>
        <p className="eyebrow">
          {i ? "راهنمای آوااستار" : "AVASTAR FIELD NOTES"}
        </p>
        <h1>{page.title[i]}</h1>
        <p>{page.intro[i]}</p>
      </header>
      <img
        src={`/images/${page.image}-800.webp`}
        alt=""
        width="800"
        height="600"
      />
      <div className="explore-reading">
        {page.sections.map(([heading, body]) => (
          <section key={heading[0]}>
            <h2>{heading[i]}</h2>
            <p>{body[i]}</p>
          </section>
        ))}
        <a href={page.to} className="account-button">
          {page.cta[i]} ↗
        </a>
        <nav
          className="explore-related"
          aria-label={i ? "راهنماهای مرتبط" : "Related guides"}
        >
          {Object.entries(explorePages)
            .filter(([key]) => key !== section)
            .map(([key, item]) => (
              <a key={key} href={`/${key}`}>
                {item.title[i]} ↗
              </a>
            ))}
        </nav>
      </div>
    </article>
  );
}
